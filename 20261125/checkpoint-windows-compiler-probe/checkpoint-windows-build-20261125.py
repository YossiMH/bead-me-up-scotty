#!/usr/bin/env python3
"""Measure a tiny MSVC compiler tree inside the reviewed, inherited Windows Job."""
import argparse
import ctypes
from ctypes import wintypes
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import time

BUILD_HELPER_SHA256 = "eabf191e85c267ebe0ef8a758a29f4fbc0187960e3e7f18a35bbb3b02d77d136"
TARGET = "x86_64-pc-windows-msvc"
WORK_SECONDS = 180
FIXTURE_FILES = {
    "Cargo.toml": '[package]\nname = "owned-compiler-probe"\nversion = "0.0.0"\nedition = "2021"\n',
    "Cargo.lock": '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "owned-compiler-probe"\nversion = "0.0.0"\n',
    "build.rs": 'fn main() {}\n',
    "src/main.rs": 'fn main() {}\n',
}


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


class Observations:
    """Hold identities for this fixture's Job descendants, including exited parents."""
    def __init__(self, B, runner, since, deadline):
        self.B, self.runner, self.since, self.deadline = B, runner, since, deadline
        self.kernel = runner.owned_baseline.kernel
        self.handles, self.records, self.samples, self.image_hashes = {}, {}, [], {}
        self.kernel.GetHandleInformation.argtypes = [wintypes.HANDLE, ctypes.POINTER(wintypes.DWORD)]
        self.kernel.GetHandleInformation.restype = wintypes.BOOL
        self.kernel.ProcessIdToSessionId.argtypes = [wintypes.DWORD, ctypes.POINTER(wintypes.DWORD)]
        self.kernel.ProcessIdToSessionId.restype = wintypes.BOOL
        self.kernel.GetExitCodeProcess.argtypes = [wintypes.HANDLE, ctypes.POINTER(wintypes.DWORD)]
        self.kernel.GetExitCodeProcess.restype = wintypes.BOOL
        self.kernel.TerminateProcess.argtypes = [wintypes.HANDLE, wintypes.UINT]
        self.kernel.TerminateProcess.restype = wintypes.BOOL

        class ProcessEntry(ctypes.Structure):
            _fields_ = [("dwSize", wintypes.DWORD), ("cntUsage", wintypes.DWORD),
                        ("th32ProcessID", wintypes.DWORD), ("th32DefaultHeapID", ctypes.c_size_t),
                        ("th32ModuleID", wintypes.DWORD), ("cntThreads", wintypes.DWORD),
                        ("th32ParentProcessID", wintypes.DWORD), ("pcPriClassBase", wintypes.LONG),
                        ("dwFlags", wintypes.DWORD), ("szExeFile", wintypes.WCHAR * 260)]
        self.ProcessEntry = ProcessEntry
        for name in ("Process32FirstW", "Process32NextW"):
            function = getattr(self.kernel, name)
            function.argtypes = [wintypes.HANDLE, ctypes.POINTER(ProcessEntry)]
            function.restype = wintypes.BOOL

    def birth(self, handle, pid):
        require(self.kernel.GetProcessId(handle) == pid, "Held process PID changed")
        values = [wintypes.FILETIME() for _ in range(4)]
        require(self.kernel.GetProcessTimes(handle, *(ctypes.byref(x) for x in values)),
                "Cannot read held process creation time")
        return (int(values[0].dwHighDateTime) << 32) | int(values[0].dwLowDateTime)

    def member(self, handle):
        # The complete NULL QueryInformationJobObject query selects this
        # Python's immediate Job; retain the process handle across that query.
        pid = self.kernel.GetProcessId(handle)
        require(pid > 0, "Cannot identify held process for exact Job query")
        return pid in self.B.job_pids()

    def parents(self, wanted):
        snapshot = self.kernel.CreateToolhelp32Snapshot(2, 0)
        require(snapshot not in (None, 0, ctypes.c_void_p(-1).value), "Cannot read process snapshot")
        rows = {}
        try:
            entry = self.ProcessEntry()
            entry.dwSize = ctypes.sizeof(entry)
            present = self.kernel.Process32FirstW(snapshot, ctypes.byref(entry))
            examined = 0
            while present:
                examined += 1
                require(examined <= 8192, "Process snapshot exceeds its bound")
                pid = int(entry.th32ProcessID)
                if pid in wanted:
                    require(pid not in rows, "Duplicate process snapshot entry")
                    rows[pid] = {"parent_pid": int(entry.th32ParentProcessID), "image_name": entry.szExeFile}
                present = self.kernel.Process32NextW(snapshot, ctypes.byref(entry))
            require(ctypes.get_last_error() == 18, "Process snapshot ended unexpectedly")
        finally:
            self.kernel.CloseHandle(snapshot)
        return rows

    def capture(self, pid, parent_row, label):
        handle = self.kernel.OpenProcess(0x1000 | 0x100000 | 0x0001, False, pid)
        if not handle:
            require(pid not in self.B.job_pids(), "A live owned process could not be retained")
            return
        try:
            flags = wintypes.DWORD()
            require(self.kernel.GetHandleInformation(handle, ctypes.byref(flags)) and not flags.value & 1,
                    "Diagnostic process handle must be non-inheritable")
            born = self.birth(handle, pid)
            key = str(pid) + ":" + str(born)
            if key in self.handles:
                return
            if self.kernel.WaitForSingleObject(handle, 0) == 0:
                return
            require(self.member(handle) and born >= self.since, "Observed process is outside this compiler attempt")
            require(parent_row is not None, "A live owned process has no snapshot identity")
            image, size = ctypes.create_unicode_buffer(32768), wintypes.DWORD(32768)
            require(self.kernel.QueryFullProcessImageNameW(handle, 0, image, ctypes.byref(size)), "Cannot read process image")
            path = self.B.safe_existing(Path(image.value))
            require(path.stat().st_size <= 64 * 1024 * 1024, "Process image exceeds hash bound")
            path_key = str(path).casefold()
            if path_key not in self.image_hashes:
                self.image_hashes[path_key] = self.B.file_hash(path)
            session = wintypes.DWORD()
            require(self.kernel.ProcessIdToSessionId(pid, ctypes.byref(session)), "Cannot read process session")
            require(len(self.handles) < 128, "Compiler process identity bound exceeded")
            self.records[key] = {"pid": pid, "creation_filetime": str(born), **parent_row,
                                 "image_path": str(path), "image_sha256": self.image_hashes[path_key],
                                 "session_id": session.value, "first_observed": self.B.utc(),
                                 "first_phase": label, "held_query_sync_terminate_handle": True,
                                 "handle_inheritable": False, "exit_code": None}
            self.handles[key] = handle
            handle = None
        finally:
            if handle:
                self.kernel.CloseHandle(handle)

    def sample(self, label):
        require(time.monotonic() < self.deadline, "Compiler probe deadline expired")
        members = self.B.job_pids()
        baseline = self.runner.baseline
        require(baseline <= members and self.runner.owned_baseline.matches(baseline), "Owned baseline changed")
        extras = members - baseline
        require(len(extras) <= 32, "Too many simultaneous compiler descendants")
        known_live = {self.records[key]["pid"] for key, handle in self.handles.items()
                      if self.kernel.WaitForSingleObject(handle, 0) == 258}
        missing = extras - known_live
        parent_rows = self.parents(missing) if missing else {}
        for pid in sorted(missing):
            self.capture(pid, parent_rows.get(pid), label)
        for key, handle in self.handles.items():
            row = self.records[key]
            require(self.birth(handle, row["pid"]) == int(row["creation_filetime"]), "Retained process birth changed")
            wait = self.kernel.WaitForSingleObject(handle, 0)
            require(wait in (0, 258), "Unexpected process wait result")
            if wait == 0 and row["exit_code"] is None:
                code = wintypes.DWORD()
                require(self.kernel.GetExitCodeProcess(handle, ctypes.byref(code)), "Cannot read owned exit code")
                row["exit_code"], row["exit_observed"] = code.value, self.B.utc()
        now = self.B.utc()
        if self.samples and self.samples[-1]["phase"] == label and self.samples[-1]["job_pids"] == sorted(members):
            self.samples[-1]["last_observed"] = now
            self.samples[-1]["complete_reads"] += 1
        else:
            require(len(self.samples) < 256, "Compiler observation bound exceeded")
            self.samples.append({"phase": label, "first_observed": now, "last_observed": now,
                                 "complete_reads": 1, "job_pids": sorted(members), "extra_pids": sorted(extras)})
        return extras

    def cleanup(self):
        extras = self.sample("cleanup-before")
        for key, handle in self.handles.items():
            row = self.records[key]
            if self.kernel.WaitForSingleObject(handle, 0) == 0:
                continue
            require(row["pid"] in extras and row["pid"] not in self.runner.baseline
                    and self.birth(handle, row["pid"]) == int(row["creation_filetime"])
                    and self.member(handle), "Cleanup refused a changed or unowned identity")
            row["cleanup_action"] = "TerminateProcess on this retained owned handle"
            row["cleanup_requested"] = self.B.utc()
            if not self.kernel.TerminateProcess(handle, 137):
                require(self.kernel.WaitForSingleObject(handle, 0) == 0, "Owned termination failed")
        until = min(self.deadline, time.monotonic() + 5)
        while self.sample("cleanup-after") and time.monotonic() < until:
            time.sleep(0.05)
        require(self.runner.owned_baseline.matches(self.B.job_pids()), "Compiler descendants remain after bounded cleanup")
        require(all(self.kernel.WaitForSingleObject(h, 0) == 0 for h in self.handles.values()),
                "A retained compiler handle survived cleanup")

    def close(self):
        for handle in self.handles.values():
            self.kernel.CloseHandle(handle)
        self.handles.clear()


def main():
    parser = argparse.ArgumentParser()
    for name in ("inputs", "inputs-sha256", "helper-sha256", "checkout"):
        parser.add_argument("--" + name, required=True)
    args = parser.parse_args()
    require(sys.platform == "win32" and ctypes.sizeof(ctypes.c_void_p) == 8, "Windows x64 is required")
    require(digest(__file__) == args.helper_sha256 and digest(args.inputs) == args.inputs_sha256,
            "Exact probe helper or input bytes differ")
    request = json.loads(Path(args.inputs).read_text())
    require(request["schema_version"] == 1 and request["operation"] == "owned-msvc-compiler-lifecycle-probe"
            and request["reviewed_build_helper_sha256"] == BUILD_HELPER_SHA256
            and request["target"] == TARGET and request["work_seconds"] == WORK_SECONDS,
            "Unexpected compiler probe contract")
    require(request["fixture_files"] == {name: hashlib.sha256(text.encode()).hexdigest() for name, text in FIXTURE_FILES.items()},
            "Probe fixture differs from reviewed bytes")
    sys.dont_write_bytecode = True
    helper = Path(__file__).with_name("reviewed-build-helper.py")
    require(digest(helper) == BUILD_HELPER_SHA256, "Reviewed helper differs before import")
    spec = importlib.util.spec_from_file_location("reviewed_checkpoint_build", helper)
    B = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(B)
    B.safe_existing(Path(args.checkout), directory=True)
    temp = B.safe_existing(Path(os.environ["RUNNER_TEMP"]), directory=True)
    token = os.environ["GITHUB_RUN_ID"] + "-" + os.environ["GITHUB_RUN_ATTEMPT"]
    require(re.fullmatch(r"[0-9]+-[1-9][0-9]*", token), "Invalid producing run identity")
    root = temp / ("bead-checkpoint-windows-build-" + token)
    require(not root.exists(), "Fresh compiler probe root already exists")
    root.mkdir()
    for name in ("logs", "tmp", "target", "fixture"):
        (root / name).mkdir()
    started = time.monotonic()
    deadline = started + WORK_SECONDS
    result = {"schema_version": 1, "status": "failed", "operation": request["operation"],
              "run": {"id": os.environ["GITHUB_RUN_ID"], "attempt": os.environ["GITHUB_RUN_ATTEMPT"],
                      "repository": os.environ["GITHUB_REPOSITORY"], "workflow_commit": os.environ["GITHUB_SHA"]},
              "helper_sha256": args.helper_sha256, "input_sha256": args.inputs_sha256,
              "reviewed_build_helper_sha256": BUILD_HELPER_SHA256, "work_seconds": WORK_SECONDS,
              "product_source_compiled": False, "fixture_main_executed": False, "tests_executed": False,
              "cargo_build_script": "Cargo may execute the exact empty fixture build script during compilation",
              "started": B.utc(), "build_root": str(root), "fixture_files": request["fixture_files"],
              "observations": [], "cleanup": []}
    B.write_json(root / "attempt-started.json", result)
    runner, process, observation = None, None, None
    try:
        runner = B.Runner(root, B.clean_environment(root), deadline)
        result["owned_job_baseline"] = runner.baseline_record
        result["visual_cpp"] = B.activate_msvc(runner, root)
        runner.run(["rustup", "toolchain", "install", "1.100.0", "--profile", "minimal",
                    "--target", TARGET, "--no-self-update"], root, "rustup", 60)
        rustc = runner.run(["rustc", "--version"], root, "rustc-version").read_text().strip()
        cargo = runner.run(["cargo", "--version"], root, "cargo-version").read_text().strip()
        host = runner.run(["rustc", "-vV"], root, "rustc-host").read_text()
        require(re.fullmatch(r"rustc 1\.100\.0 \([^\r\n]+\)", rustc)
                and re.fullmatch(r"cargo 1\.100\.0 \([^\r\n]+\)", cargo)
                and re.search(r"(?m)^host: " + re.escape(TARGET) + r"\s*$", host), "Pinned toolchain differs")
        result["toolchain"] = {"rustc": rustc, "cargo": cargo, "host": TARGET}
        fixture = root / "fixture"
        for name, text in FIXTURE_FILES.items():
            path = fixture / name
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("x", newline="\n") as stream:
                stream.write(text)
        bash = B.safe_existing(Path(os.environ["ProgramFiles"]) / "Git" / "bin" / "bash.exe")
        for label, command in (("fixture-release", "cargo build --release --locked --target " + TARGET),
                               ("fixture-tests-no-run", "cargo test --locked --no-run --target " + TARGET)):
            require(runner.owned_baseline.matches(B.job_pids()), "Fixture command lacks exact quiescent baseline")
            require(time.monotonic() + 18 < deadline, "No bounded compiler work time remains")
            stamp = wintypes.FILETIME()
            kernel = runner.owned_baseline.kernel
            kernel.GetSystemTimeAsFileTime.argtypes = [ctypes.POINTER(wintypes.FILETIME)]
            kernel.GetSystemTimeAsFileTime.restype = None
            kernel.GetSystemTimeAsFileTime(ctypes.byref(stamp))
            since = (int(stamp.dwHighDateTime) << 32) | int(stamp.dwLowDateTime)
            observation = Observations(B, runner, since, deadline - 3)
            record = {"label": label, "args": [str(bash), "-c", command], "cwd": str(fixture),
                      "started": B.utc(), "start_filetime": str(since), "baseline_pids": sorted(runner.baseline)}
            result["observations"].append(record)
            B.write_json(root / "logs" / (label + ".started.json"), record)
            try:
                with (root / "logs" / (label + ".stdout")).open("xb") as stdout, (root / "logs" / (label + ".stderr")).open("xb") as stderr:
                    process = subprocess.Popen(record["args"], cwd=fixture, env=runner.env, stdin=subprocess.DEVNULL,
                                               stdout=stdout, stderr=stderr, creationflags=subprocess.CREATE_NO_WINDOW)
                    record["pid"] = process.pid
                    until = min(deadline - 18, time.monotonic() + 60)
                    while process.poll() is None:
                        observation.sample(label + ":running")
                        require(time.monotonic() < until, "Fixture compiler exceeded its deadline")
                        require(os.fstat(stdout.fileno()).st_size <= 4 * 1024 * 1024
                                and os.fstat(stderr.fileno()).st_size <= 4 * 1024 * 1024,
                                "Fixture compiler stream bound exceeded")
                        time.sleep(0.1)
                    record["exit_code"] = process.returncode
                    stdout.flush(); stderr.flush()
                    os.fsync(stdout.fileno()); os.fsync(stderr.fileno())
                    require(os.fstat(stdout.fileno()).st_size <= 4 * 1024 * 1024
                            and os.fstat(stderr.fileno()).st_size <= 4 * 1024 * 1024,
                            "Final fixture compiler stream bound exceeded")
                require(process.returncode == 0, "Fixture compiler failed")
                require(time.monotonic() + 13 < deadline, "No full observation and cleanup budget remains")
                observe_until = time.monotonic() + 5
                while True:
                    extras = observation.sample(label + ":after-exit")
                    if time.monotonic() >= observe_until:
                        break
                    time.sleep(0.25)
                record["persistent_pids_after_five_seconds"] = sorted(extras)
            finally:
                observation.cleanup()
                record["samples"] = observation.samples
                record["processes"] = list(observation.records.values())
                record["final_job_pids"] = sorted(B.job_pids())
                record["finished"] = B.utc()
                B.write_json(root / "logs" / (label + ".exit.json"), record)
                observation.close()
                observation = None
                process = None
            result["cleanup"].append({"label": label, "exact_baseline_restored": True})
        require(all(digest(fixture / name) == pin for name, pin in request["fixture_files"].items()),
                "Fixture input bytes changed")
        require(digest(helper) == BUILD_HELPER_SHA256 and digest(__file__) == args.helper_sha256
                and digest(args.inputs) == args.inputs_sha256, "Probe inputs changed")
        require(runner.owned_baseline.matches(B.job_pids()), "Final owned baseline differs")
        result["status"] = "passed"
    except BaseException as error:
        result["error"] = type(error).__name__ + ": " + str(error)
    finally:
        if observation is not None:
            try:
                observation.cleanup()
            except BaseException as error:
                result["cleanup_error"] = type(error).__name__ + ": " + str(error)
            result["unfinished_observation"] = {"samples": observation.samples,
                                                "processes": list(observation.records.values())}
            observation.close()
        if process is not None:
            try:
                process.wait(timeout=2)
            except subprocess.TimeoutExpired:
                result["cleanup_error"] = "Fixture command remains for outer Job cleanup"
        result["commands"] = runner.commands if runner else []
        result["job_query_retries"] = B.JOB_QUERY_RETRIES
        result["finished"] = B.utc()
        result["duration_seconds"] = round(time.monotonic() - started, 3)
        if time.monotonic() >= deadline or "cleanup_error" in result:
            result["status"] = "failed"
        B.write_json(root / "build-result.json", result)
        B.write_json(root / "result.json", {"schema_version": 1, "status": result["status"],
                     "operation": request["operation"], "build_result_sha256": digest(root / "build-result.json"),
                     "product_qualification": False, "outer_windows_job_closure_required": True})
        B.emit_receipt("CHECKPOINT_WINDOWS_COMPILER_PROBE", root / "build-result.json")
        B.emit_receipt("CHECKPOINT_WINDOWS_BUILD_OUTER", root / "result.json")
        B.emit_small_streams(root, root / "logs")
    return 0 if result["status"] == "passed" else 1


if __name__ == "__main__":
    raise SystemExit(main())
